"""
NetCDF input version of test_gwf_rch01: flopy4 re-writes the simulation with
NetCDF package arrays, and the run is compared to the ASCII run and
re-checked. The base test's own regression check (budget node/q values) is
sensitive to RCHA's IRCH routing by design, so it also verifies IRCH is read
back correctly from NetCDF without a separate explicit check.

NetCDF input generated by: flopy4.
"""

import pytest
from compare import Comparison
from framework import TestFramework, require_flopy4, write_fp4_netcdf
from test_gwf_rch01 import build_models, cases


@pytest.mark.netcdf
@pytest.mark.fp4
@pytest.mark.parametrize(
    "idx, name",
    list(enumerate(cases)),
)
@pytest.mark.parametrize("compare", [Comparison.FP4_STRUCTURED, Comparison.FP4_LAYERED])
def test_mf6model_fp4(idx, name, function_tmpdir, targets, compare):
    """The base test re-written by flopy4 with NetCDF input matches the ASCII run."""
    from test_gwf_rch01 import check_output as check

    def check_both(test):
        check(idx, test)
        test.workspace = test.workspace / compare.value
        check(idx, test)

    test = TestFramework(
        name=name,
        workspace=function_tmpdir,
        build=lambda t: build_models(idx, t),
        check=check_both,
        targets=targets,
        compare=compare,
    )
    test.run()


def check_legacy_mesh_attr(idx, test):
    """Backward compatibility: a UGRID NetCDF input file carrying only the
    legacy unprefixed `mesh` global attribute (as written by MF6 versions
    before the modflow_mesh rename) must still be read correctly.
    """
    import flopy
    import netCDF4 as nc
    from test_gwf_rch01 import check_output as check

    fp4_ws = test.workspace / Comparison.FP4_LAYERED.value
    write_fp4_netcdf(test.workspace, fp4_ws, "layered")

    with nc.Dataset(fp4_ws / "rch.input.nc", "r+") as ds:
        value = ds.getncattr("modflow_mesh")
        ds.delncattr("modflow_mesh")
        ds.setncattr("mesh", value)

    success, buff = flopy.run_model(
        test.targets["mf6"],
        fp4_ws / "mfsim.nam",
        model_ws=fp4_ws,
        report=True,
    )
    assert success, "legacy mesh attr re-run failed"
    test.success = success
    test.workspace = fp4_ws
    check(idx, test)


@pytest.mark.netcdf
@pytest.mark.fp4
def test_mf6model_fp4_legacy_mesh_attr(function_tmpdir, targets):
    """A flopy4-generated NetCDF input file carrying only the legacy
    unprefixed `mesh` global attribute must still be read correctly.
    """
    require_flopy4()
    idx = 0
    test = TestFramework(
        name=cases[idx],
        workspace=function_tmpdir,
        build=lambda t: build_models(idx, t),
        check=lambda t: check_legacy_mesh_attr(idx, t),
        targets=targets,
        compare=None,
    )
    test.run()
