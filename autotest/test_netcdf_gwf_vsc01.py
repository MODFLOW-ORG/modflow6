"""
NetCDF input version of test_gwf_vsc01: flopy4 re-writes the simulations with
NetCDF package arrays, and the run is compared to the ASCII run and
re-checked. Also verifies the list-based (GHB) and array-based (GHBG)
representations agree with each other, not just with their own ASCII
baseline, since the generic FP4 comparison only ever compares a
representation against its own rewrite.

NetCDF input generated by: flopy4.
"""

import flopy
import pytest
from compare import Comparison
from framework import TestFramework
from test_gwf_vsc01 import cases


@pytest.mark.netcdf
@pytest.mark.fp4
@pytest.mark.parametrize(
    "idx, name",
    list(enumerate(cases)),
)
@pytest.mark.parametrize("compare", [Comparison.FP4_STRUCTURED, Comparison.FP4_LAYERED])
def test_mf6model_fp4(idx, name, function_tmpdir, targets, compare):
    """The base test re-written by flopy4 with NetCDF input matches the
    ASCII run, and the list-based and array-based representations agree
    with each other.
    """
    from test_gwf_vsc01 import build_models as build
    from test_gwf_vsc01 import check_output, check_outputs

    def check_both(test):
        check_outputs(idx, test)
        list_ws = test.workspace / compare.value
        array_ws = list_ws / "mf6"
        check_output(idx, list_ws)
        check_output(idx, array_ws, array_input=True)

        # the generic FP4 comparison only ever checks a representation
        # against its own ASCII baseline; list-based (GHB) and array-based
        # (GHBG) must also agree with each other
        for mname, text, ext in (
            (f"gwf-{name}", "head", "hds"),
            (f"gwt-{name}", "concentration", "ucn"),
        ):
            success = flopy.utils.compare.compare_heads(
                None,
                None,
                text=text,
                outfile=str(array_ws / f"{mname}.{ext}.cmp.out"),
                files1=str(list_ws / f"{mname}.{ext}"),
                files2=str(array_ws / f"{mname}.{ext}"),
                difftol=True,
            )
            assert success, f"list vs array {text} comparison failed"

    test = TestFramework(
        name=name,
        workspace=function_tmpdir,
        build=lambda t: build(idx, t),
        check=check_both,
        targets=targets,
        compare=compare,
    )
    test.run()
