def build_models(idx, test):
    name = cases[idx]
    accel = linear_accel[idx]
    relax = relax_factors[idx]
    cmp_ws = Path(test.workspace) / cmp_prefix

    disv_props, xcell, ycell = _build_voronoi_grid(nx_seeds, ny_seeds, lx, ly, seed=42)

    amg_sim = _build_amg_sim(
        name, test.workspace, accel, relax, disv_props, xcell, ycell
    )
    ilu_sim = _build_ilu_sim(name, cmp_ws, accel, relax, disv_props, xcell, ycell)
    return amg_sim, ilu_sim


def check_output(idx, test):
    name = cases[idx]

    hds_amg = flopy.utils.HeadFile(Path(test.workspace) / f"{name}.hds").get_alldata()

    hds_ilu = flopy.utils.HeadFile(
        Path(test.workspace) / cmp_prefix / f"{name}.hds"
    ).get_alldata()

    assert hds_amg.shape == hds_ilu.shape, (
        f"Head array shapes differ: AMG {hds_amg.shape} vs ILU {hds_ilu.shape}"
    )

    max_diff = np.max(np.abs(hds_amg - hds_ilu))
    assert max_diff < htol, (
        f"AMG and ILU heads differ by {max_diff:.3e} m (tolerance {htol:.3e} m)"
    )

    # Iteration comparison only for the CG (SPD) case.  For the BiCGSTAB case
    # the confined steady-state Voronoi grid is small enough that ILUT can
    # compete on iteration count; the meaningful check is head agreement.
    if linear_accel[idx] == "cg":
        amg_iters = count_inner_iters(Path(test.workspace) / f"{name}_outer.csv")
        ilu_iters = count_inner_iters(
            Path(test.workspace) / cmp_prefix / f"{name}_outer.csv"
        )
        assert amg_iters < ilu_iters, (
            f"AMG total inner iterations ({amg_iters}) >= ILU ({ilu_iters})"
        )


@pytest.mark.skipif(
    not HAS_VORONOI_DEPS,
    reason="scipy and shapely are required for Voronoi grid generation",
)
@pytest.mark.parametrize("idx, name", enumerate(cases))
def test_mf6model(idx, name, function_tmpdir, targets):
    test = TestFramework(
        name=name,
        workspace=function_tmpdir,
        targets=targets,
        build=lambda t: build_models(idx, t),
        check=lambda t: check_output(idx, t),
        overwrite=False,
        compare=None,
    )
    test.run()
